import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { rolldown } from "rolldown";

// Compile the shared service source once; never maintain a second Deno copy.
const dependencies = JSON.parse(
  await readFile("package-lock.json", "utf8"),
).packages;
const external = Object.fromEntries(
  ["@supabase/supabase-js", "zod"].map((name) => [
    name,
    `npm:${name}@${dependencies[`node_modules/${name}`].version}`,
  ]),
);
const build = await rolldown({
  input: "supabase/functions/studio-api/entry.ts",
  external: Object.keys(external),
  resolve: { alias: { "@": resolve(".") } },
  plugins: [
    {
      name: "backend-runtime-boundary",
      resolveId(source) {
        if (
          source === "react" ||
          source === "server-only" ||
          source.startsWith("next/")
        ) {
          throw new Error(`Frontend dependency in Edge API: ${source}`);
        }
      },
    },
  ],
});
const { output } = await build.generate({ format: "esm", paths: external });
if (output.length !== 1 || output[0].type !== "chunk")
  throw new Error("Expected a single Edge API module");
const code = `// Generated by npm run build:edge. Edit lib/backend or entry.ts instead.\n${output[0].code}`;
if (/\bprocess\.env\b/.test(code))
  throw new Error("Node environment access in Edge API");
const target = "supabase/functions/studio-api/index.js";
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== code)
    throw new Error("Edge API is stale. Run npm run build:edge.");
} else {
  await writeFile(target, code);
}
await build.close();
console.log(
  `Edge API: ${Buffer.byteLength(code)} bytes; pinned SDK and validation imports.`,
);
